#!/bin/bash
set -euo pipefail

# ==============================================================================
# GACHIMURA 단일 서버 무중단 배포(Zero-Downtime Deployment) 스크립트
# 아키텍처: Docker Compose + Nginx Upstream Dynamic Reload (Blue-Green)
# 다운타임: 0.x초 (Nginx graceful reload)
# 롤백: 헬스체크 실패 시 신규 컨테이너 자동 폐기 및 기존 컨테이너 유지 (장애 0초)
# ==============================================================================

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_DIR="$(dirname "${SCRIPT_DIR}")"
CONF_DIR="${PROJECT_DIR}/nginx/conf.d"
UPSTREAM_CONF="${CONF_DIR}/upstream.conf"

cd "${PROJECT_DIR}"

mkdir -p "${CONF_DIR}"

echo "=============================================================================="
echo "🚀 [GACHIMURA] 무중단 배포 프로세스 시작"
echo "=============================================================================="

# 1. Base 인프라(MySQL DB, Nginx) 가동 확인
echo ">>> [1/7] Base 인프라(DB, Nginx) 상태 확인 및 가동..."
docker compose -f docker-compose.base.yml up -d

# 2. 현재 실행 중인 활성 환경(Active) 파악
IS_BLUE_RUNNING=$(docker ps --filter "name=gachimura-backend-blue" --filter "status=running" -q || true)
IS_GREEN_RUNNING=$(docker ps --filter "name=gachimura-backend-green" --filter "status=running" -q || true)

if [ -n "$IS_BLUE_RUNNING" ] && [ -z "$IS_GREEN_RUNNING" ]; then
    CURRENT="blue"
    TARGET="green"
    TARGET_BACKEND_PORT=3002
    TARGET_FRONTEND_PORT=4002
    TARGET_BACKEND_HOST="gachimura-backend-green"
    TARGET_FRONTEND_HOST="gachimura-frontend-green"
elif [ -n "$IS_GREEN_RUNNING" ]; then
    CURRENT="green"
    TARGET="blue"
    TARGET_BACKEND_PORT=3001
    TARGET_FRONTEND_PORT=4001
    TARGET_BACKEND_HOST="gachimura-backend-blue"
    TARGET_FRONTEND_HOST="gachimura-frontend-blue"
else
    # 최초 배포 시 (둘 다 미기동 상태)
    CURRENT="none"
    TARGET="blue"
    TARGET_BACKEND_PORT=3001
    TARGET_FRONTEND_PORT=4001
    TARGET_BACKEND_HOST="gachimura-backend-blue"
    TARGET_FRONTEND_HOST="gachimura-frontend-blue"
fi

echo ">>> [2/7] 현재 활성 환경: [${CURRENT}] ➡️ 신규 배포 대상: [${TARGET}]"

# 3. 신규 Target 환경 빌드 및 기동
echo ">>> [3/7] [${TARGET}] 컨테이너 빌드 및 기동 시작..."
docker compose -f "docker-compose.${TARGET}.yml" up -d --build

# 4. Health Check (최대 60초 대기)
echo ">>> [4/7] [${TARGET}] 서비스 Health Check 시작 (최대 60초)..."
MAX_RETRIES=30
RETRY_INTERVAL=2

# 4-1. 백엔드 헬스체크 (/api/health)
BACKEND_HEALTHY=false
for i in $(seq 1 $MAX_RETRIES); do
    # NestJS 전역 접두사 /api 적용: /api/health 우선 확인 후 /health 폴백
    STATUS=$(curl -s -o /dev/null -w "%{http_code}" "http://127.0.0.1:${TARGET_BACKEND_PORT}/api/health" || true)
    if [ "$STATUS" != "200" ]; then
        STATUS=$(curl -s -o /dev/null -w "%{http_code}" "http://127.0.0.1:${TARGET_BACKEND_PORT}/health" || true)
    fi

    if [ "$STATUS" = "200" ]; then
        echo "  ✅ Backend Health Check 성공! (HTTP 200, 시도: ${i}/${MAX_RETRIES})"
        BACKEND_HEALTHY=true
        break
    fi
    echo "  ⏳ Backend 응답 대기 중 (HTTP ${STATUS:-N/A}, 시도: ${i}/${MAX_RETRIES})..."
    sleep $RETRY_INTERVAL
done

# 4-2. 프론트엔드 헬스체크 (/)
FRONTEND_HEALTHY=false
if [ "$BACKEND_HEALTHY" = "true" ]; then
    for i in $(seq 1 $MAX_RETRIES); do
        STATUS=$(curl -s -o /dev/null -w "%{http_code}" "http://127.0.0.1:${TARGET_FRONTEND_PORT}/" || true)
        if [ "$STATUS" = "200" ] || [ "$STATUS" = "301" ] || [ "$STATUS" = "302" ] || [ "$STATUS" = "307" ] || [ "$STATUS" = "308" ]; then
            echo "  ✅ Frontend Health Check 성공! (HTTP ${STATUS}, 시도: ${i}/${MAX_RETRIES})"
            FRONTEND_HEALTHY=true
            break
        fi
        echo "  ⏳ Frontend 응답 대기 중 (HTTP ${STATUS:-N/A}, 시도: ${i}/${MAX_RETRIES})..."
        sleep $RETRY_INTERVAL
    done
fi

# 5. 헬스체크 실패 시 즉시 자동 롤백
if [ "$BACKEND_HEALTHY" != "true" ] || [ "$FRONTEND_HEALTHY" != "true" ]; then
    echo "🚨 [ERROR] [${TARGET}] 서비스 Health Check 실패! 즉시 자동 롤백을 수행합니다."
    echo "--- Backend Logs ---"
    docker logs --tail 30 "gachimura-backend-${TARGET}" || true
    echo "--- Frontend Logs ---"
    docker logs --tail 30 "gachimura-frontend-${TARGET}" || true

    echo ">>> 신규 [${TARGET}] 컨테이너 폐기 중..."
    docker compose -f "docker-compose.${TARGET}.yml" down
    if [ "$CURRENT" != "none" ]; then
        echo ">>> 기존 [${CURRENT}] 환경이 계속 서비스 중이므로 장애 없이 유지됩니다."
    fi
    exit 1
fi

# 6. Nginx Upstream 포트 스위칭 (0.x초 무중단 Reload)
echo ">>> [5/7] Nginx Upstream을 [${TARGET}]으로 전환 중..."
cat << EOF > "${UPSTREAM_CONF}"
# Auto-generated by deploy.sh at $(date)
upstream backend_server {
    server ${TARGET_BACKEND_HOST}:3000;
    keepalive 32;
}

upstream frontend_server {
    server ${TARGET_FRONTEND_HOST}:3000;
    keepalive 32;
}
EOF

# Nginx 컨테이너 무중단 reload
docker exec gachimura-nginx nginx -s reload
echo "  ✅ Nginx 리로드 완료! 실시간 트래픽이 [${TARGET}]으로 전환되었습니다. (다운타임 0.x초)"

# 7. 이전(Current) 환경 정리 및 이미지 Prune
if [ "$CURRENT" != "none" ]; then
    echo ">>> [6/7] 이전 환경 [${CURRENT}] 정상 종료 대기 (진행 중인 커넥션 보호 5초)..."
    sleep 5
    docker compose -f "docker-compose.${CURRENT}.yml" down
    echo "  ✅ 이전 환경 [${CURRENT}] 컨테이너 안전 종료 완료."
else
    echo ">>> [6/7] 최초 마이그레이션 배포 완료. 기존 레거시 컨테이너(prod) 정리..."
    docker compose -f docker-compose.prod.yml down --remove-orphans 2>/dev/null || true
fi

echo ">>> [7/7] 미사용 도커 이미지 정리 (Docker image prune)..."
docker image prune -f

echo "=============================================================================="
echo "🎉 [GACHIMURA] 무중단 배포 완료! [${TARGET}] 환경 가동 중"
echo "=============================================================================="
